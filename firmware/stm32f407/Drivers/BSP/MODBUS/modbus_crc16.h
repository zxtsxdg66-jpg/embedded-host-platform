/**
 ****************************************************************************************************
 * @file        modbus_crc16.h
 * @brief       Modbus RTU 标准 CRC16（多项式 0xA001，初始值 0xFFFF，逐位算法，输出低字节在前）。
 *
 * 已用文档《噪声检测模块(HH_07.06)应用手册V1.2》3.3.2 节给出的真实报文示例交叉核对：
 *   请求帧 01 03 00 00 00 01 -> CRC 低字节 0x84 高字节 0x0A（与手册"84 0A"一致）
 *   响应帧 01 03 02 01 9E    -> CRC 低字节 0x38 高字节 0x7C（与手册"38 7C"一致）
 * 该算法与 厂商资料中厂商提供的参考实现（CRC16.c，查表版 usMBCRC16）
 * 在数学上等价，仅实现方式不同（逐位 vs 查表），结果对任意输入完全一致。
 ****************************************************************************************************
 */
#ifndef __MODBUS_CRC16_H
#define __MODBUS_CRC16_H

#include <stdint.h>

/**
 * @brief   计算 Modbus RTU CRC16
 * @param   data    数据起始地址
 * @param   length  数据长度
 * @retval  16 位 CRC 值（主机字节序，非报文字节序；写入报文时低字节在前、高字节在后）
 */
uint16_t modbus_crc16_calculate(const uint8_t *data, uint16_t length);

#endif
