"""Minimal smoke test for scripts/run_gui.py's Simulator- and Hardware-mode
composition functions.

Confirms:
- a QApplication can exist in this process
- MainWindow can be constructed and shown against the launcher's own
  build_simulator_runtime()/build_hardware_runtime() composition
- data generated by the registered SimulatorDevice reaches the UI
- Hardware mode wires SerialChannel -> HardwareDeviceReceiver ->
  HardwareRuntimeRunner into the *same* ApplicationRuntime.data_service
  MainController/UI already read from, and that a manual runner.run_once()
  (standing in for what a QTimer would call repeatedly) delivers data to
  the UI exactly like Simulator mode does

Does not call scripts.run_gui.main() itself: main() calls app.exec(),
which blocks the process running the GUI event loop until the window is
closed. Instead this test reuses main()'s own composition helpers and
drives MainWindow directly -- exactly how tests/ui/test_main_window.py
already exercises MainWindow elsewhere in this suite. Hardware mode is
exercised with mocked pyserial (same technique as
tests/communication/test_serial.py), since no real hardware is available.
"""

