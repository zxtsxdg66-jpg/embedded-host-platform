class _FakeSerialPort:
    """Minimal virtual stand-in for serial.Serial (mirrors
    tests/communication/test_serial.py's own fake). Reads and writes share
    one buffer, modeling "bytes written to the wire are what get read back"
    for test purposes."""

    def __init__(self) -> None:
        self.is_open = True
        self.buffer = bytearray()

    def write(self, data: bytes) -> int:
        self.buffer.extend(data)
        return len(data)

    @property
    def in_waiting(self) -> int:
        return len(self.buffer)

    def read(self, size: int) -> bytes:
        chunk = bytes(self.buffer[:size])
        del self.buffer[:size]
        return chunk

    def close(self) -> None:
        self.is_open = False


def _build_hardware_runtime_with_mocked_serial():
    with patch(
        "communication.serial.list_ports.comports",
        return_value=[SimpleNamespace(device="COM3")],
    ):
        with patch(
            "communication.serial.serial.Serial", return_value=_FakeSerialPort()
        ):
            return build_hardware_runtime(port="COM3", device_id="mcu-1")


def test_build_hardware_runtime_registers_the_remote_device(qtbot) -> None:
    runtime, _runner = _build_hardware_runtime_with_mocked_serial()
    assert runtime.list_devices() == ["mcu-1"]


def test_build_hardware_runtime_runner_starts_not_running(qtbot) -> None:
    _runtime, runner = _build_hardware_runtime_with_mocked_serial()
    assert runner.running is False


def test_hardware_mode_data_reaches_the_ui_via_runner_run_once(qtbot) -> None:
    runtime, runner = _build_hardware_runtime_with_mocked_serial()
    controller = MainController(LocalApi(runtime), client_id="test-launcher")
    window = MainWindow(controller)
    qtbot.addWidget(window)
    window.show()

    window._device_list.setCurrentRow(0)
    window._control_panel._channel_input.setCurrentText("temperature")
    qtbot.mouseClick(
        window._control_panel._subscribe_button, Qt.MouseButton.LeftButton
    )

    # Simulate "the MCU wrote a data-report frame to the wire" by sending
    # through the device's registered channel, then let runner.run_once()
    # do what a QTimer tick would do in the real GUI.
    registration = runtime.devices.get("mcu-1")
    payload = json.dumps({"channel": "temperature", "value": 25.5}).encode("utf-8")
    frame = Frame(
        device_id=registration.wire_id,
        command_type=DATA_REPORT_CODE,
        payload=payload,
    )
    registration.channel.send(encode(frame))

    runner.start()
    runner.run_once()

    assert window._data_panel.row_count() == 1
    # 2026-09-18: 温度按两位小数显示（ui/channel_display.CHANNEL_DECIMALS），
    # 所以这里断言的是渲染后的文本；上链路送来的仍是 25.5 这个原值。
    assert window._data_panel._latest_table.item(0, 2).text() == "25.50"
    window.close()  # 同上：喂过数据的窗口不关，teardown 时可能崩在 paint 里


def test_hardware_mode_device_channels_are_watched_for_alarms(qtbot) -> None:
    """Regression test: build_hardware_runtime() calls
    ``runtime.devices.register(...)`` directly (to read back the wire id),
    bypassing ApplicationRuntime.register_device() -- which would
    otherwise auto-subscribe the alarm processor. build_hardware_runtime()
    must therefore call ``runtime.watch_alarms_for(device)`` itself, or
    Hardware-mode devices silently never produce any alarm/status events
    at all (caught via manual testing 2026-08-12: the WSL hardware-in-the-
    loop demo showed no alarm even for an out-of-threshold reading, while
    Simulator mode worked). See application/runtime.py's watch_alarms_for
    docstring.
    """
    from service.sensor_data_processor import ThresholdStatus

    runtime, runner = _build_hardware_runtime_with_mocked_serial()
    statuses: list[ThresholdStatus] = []
    runtime.subscribe_alarm_status(statuses.append)

    registration = runtime.devices.get("mcu-1")
    payload = json.dumps({"channel": "temperature", "value": 40.0}).encode("utf-8")
    frame = Frame(
        device_id=registration.wire_id,
        command_type=DATA_REPORT_CODE,
        payload=payload,
    )
    # 送两帧：2026-09-09 起报警需连续确认，一次越限只是嫌疑。
    registration.channel.send(encode(frame))
    registration.channel.send(encode(frame))

    runner.start()
    runner.run_once()

    assert len(statuses) == 2
    assert [s.triggered for s in statuses] == [False, True]
    assert statuses[-1].channel == "temperature"


def test_simulator_devices_each_declare_only_their_own_channel() -> None:
    """Simulator mode registers three one-channel devices, Hardware mode
    one three-channel device. A view that offers a fixed三通道 list is
    therefore wrong in Simulator mode -- two of every three choices
    subscribe to nothing while reporting success. The channel list has to
    come from the device, so it has to be observable through the API."""
    from api.local_api import LocalApi

    runtime, _ = build_simulator_runtime()
    api = LocalApi(runtime)

    seen = {
        device_id: api.get_device_status(device_id).channels
        for device_id in api.list_devices()
    }

    assert len(seen) == 3
    for channels in seen.values():
        assert len(channels) == 1
    assert sorted(c for pair in seen.values() for c in pair) == [
        "humidity",
        "noise",
        "temperature",
    ]


def test_subscribing_a_channel_the_device_lacks_yields_no_data() -> None:
    """Documents the trap the channel list exists to prevent: this is not
    an error at any layer, it simply never delivers anything."""
    from api.local_api import LocalApi

    runtime, runner = build_simulator_runtime()
    api = LocalApi(runtime)
    temperature_device = next(
        d for d in api.list_devices()
        if api.get_device_status(d).channels == ("temperature",)
    )

    received: list[object] = []
    subscription = api.subscribe_data(
        temperature_device, "humidity", received.append
    )
    runner.start()
    for _ in range(5):
        runner.run_once()

    assert subscription  # accepted without complaint
    assert received == []  # and delivers nothing, forever
