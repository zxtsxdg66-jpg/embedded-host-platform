def test_simulator_runner_drives_data_into_the_ui(qtbot) -> None:
    """The regression this guards: before 2026-08-15 nothing in the
    running application called report_data(), so Simulator mode showed a
    permanently empty window. Driving the returned runner must populate
    the data panel."""
    runtime, runner = build_simulator_runtime()
    controller = MainController(LocalApi(runtime), client_id="test-launcher")
    window = MainWindow(controller)
    qtbot.addWidget(window)
    window.show()

    window._device_list.setCurrentRow(0)
    window._control_panel._channel_input.setCurrentText("temperature")
    qtbot.mouseClick(window._control_panel._subscribe_button, Qt.MouseButton.LeftButton)

    runner.run_once()

    assert window._data_panel.row_count() == 1
    assert float(window._data_panel._latest_table.item(0, 2).text()) > 0
    # **必须收尾关窗**，不是礼貌而是防崩（2026-09-21 定位）。
    # 一个 show() 过、且刚喂进数据的窗口，会留下一个尚未处理的 paint 事件；
    # pytest-qt 在用例结束后先 _process_events()、随后销毁 addWidget 登记的
    # 控件，那个 paint 便可能落在已开始析构的控件上，表现为
    # `Windows fatal exception: access violation`，栈顶在
    # `chart_widget._draw_grid` —— 整个 pytest 进程当场死掉，**没有失败用例、
    # 没有统计行**，看起来像是随机的环境问题。
    #
    # 它对用例总数敏感：本文件之外随便再加四个用例（哪怕是 `assert True`）
    # 就能稳定复现，所以它多年来一直擦着边过。三个 show() 过窗口的用例里
    # 只有喂过数据的会崩——空图表那条 `_draw` 早早返回，画不到 _draw_grid。
    window.close()


